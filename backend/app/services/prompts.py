def build_header(ticket, max_tz_chars):
    """Шапка запроса: задача и сокращённое ТЗ (повторяется в каждом батче)."""
    if not ticket:
        return "Задача: не определена (ТЗ недоступно)."
    lines = [f"Задача: {ticket.get('key')} — {ticket.get('title') or ''}".rstrip(" —")]
    tz = (ticket.get("description") or "").strip()
    if tz:
        if len(tz) > max_tz_chars:
            tz = tz[:max_tz_chars].rsplit(" ", 1)[0] + " …"
        lines.append(f"ТЗ (кратко): {tz}")
    return "\n".join(lines)
